import { boolean, date, index, pgTable, primaryKey, text, timestamp, uuid } from 'drizzle-orm/pg-core';
import { persons } from '../people/schema';

const id = () => uuid('id').primaryKey().defaultRandom();
const createdAt = () => timestamp('created_at', { withTimezone: true }).notNull().defaultNow();

export const projects = pgTable('projects', {
  id: id(),
  name: text('name').notNull(),
  code: text('code'),
  /** ACTIVE | ARCHIVED */
  status: text('status').notNull().default('ACTIVE'),
  createdAt: createdAt(),
});

export const projectMembers = pgTable(
  'project_members',
  {
    projectId: uuid('project_id').notNull().references(() => projects.id, { onDelete: 'cascade' }),
    personId: uuid('person_id').notNull().references(() => persons.id, { onDelete: 'cascade' }),
  },
  (t) => [primaryKey({ columns: [t.projectId, t.personId] })],
);

export const attendancePeriods = pgTable(
  'attendance_periods',
  {
    id: id(),
    personId: uuid('person_id').notNull().references(() => persons.id, { onDelete: 'cascade' }),
    /** Day the period is attributed to (local). */
    date: date('date', { mode: 'string' }).notNull(),
    /** WORK | BREAK */
    type: text('type').notNull().default('WORK'),
    /** Local date-times without offset, in the company timezone. */
    startAt: timestamp('start_at', { mode: 'string' }).notNull(),
    endAt: timestamp('end_at', { mode: 'string' }),
    projectId: uuid('project_id').references(() => projects.id, { onDelete: 'set null' }),
    comment: text('comment'),
    /** pending | approved | rejected */
    status: text('status').notNull().default('approved'),
    autoGenerated: boolean('auto_generated').notNull().default(false),
    createdByUserId: uuid('created_by_user_id'),
    decidedByUserId: uuid('decided_by_user_id'),
    createdAt: createdAt(),
  },
  (t) => [index('attendance_person_date_idx').on(t.personId, t.date)],
);
